#!/usr/bin/env python3
"""Render edge config (Caddy, dnsmasq, mDNS names, portal inventory) from inventory.json.

Usage: render.py [OUT_DIR]   (default: <repo>/build/edge)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load():
    with open(os.path.join(ROOT, "inventory.json")) as f:
        return json.load(f)


def edge_node(inv):
    edges = [n for n, v in inv["nodes"].items() if v.get("edge")]
    if len(edges) != 1:
        sys.exit("inventory.json must mark exactly one node as edge")
    return edges[0]


def upstream_for(inv, svc, edge):
    """Address the edge proxies to. Remote nodes are reached on their tailnet IP."""
    if svc["node"] == edge:
        return svc["upstream"]
    port = svc["upstream"].rsplit(":", 1)[1]
    return "%s:%s" % (inv["nodes"][svc["node"]]["tailscale_ip"], port)


def caddyfile(inv):
    edge = edge_node(inv)
    e = inv["nodes"][edge]
    dom = inv["domain"]
    out = [
        "# Generated by fleet/edge/render.py from inventory.json. Do not edit on the host.",
        "",
    ]
    portal_hosts = [dom] + ["%s.%s" % (n, dom) for n in inv["portal"]["names"]]
    portal_hosts += ["%s.local" % n for n in inv["portal"]["local_names"]]
    portal_hosts += [e["lan_ip"], e["tailscale_ip"], e["tailscale_name"],
                     "%s.%s" % (e["tailscale_name"], inv["tailnet"]), "localhost", "127.0.0.1"]
    out.append(", ".join("http://" + h for h in portal_hosts) + " {")
    out.append("\tencode zstd gzip")
    out.append('\trespond /health "OK" 200')
    for name, node in inv["nodes"].items():
        target = "127.0.0.1" if name == edge else node["tailscale_ip"]
        out.append("\thandle_path /api/nodes/%s/* {" % name)
        out.append("\t\treverse_proxy %s:%d" % (target, node["agent_port"]))
        out.append("\t}")
    out.append("\thandle {")
    out.append("\t\troot * /srv/fleet-portal")
    out.append('\t\theader Cache-Control "no-cache, no-store, must-revalidate"')
    out.append("\t\tfile_server")
    out.append("\t}")
    out.append("}")
    for s in inv["services"]:
        if not s.get("name_host"):
            continue
        hosts = ["http://%s.%s" % (s["name_host"], dom), "http://%s.local" % s["name_host"]]
        out.append("")
        out.append(", ".join(hosts) + " {")
        # No response compression and immediate flushing: SSE/streaming APIs
        # (9router completions, T3 websockets, Jellyfin video) must not buffer.
        out.append("\treverse_proxy %s {" % upstream_for(inv, s, edge))
        out.append("\t\tflush_interval -1")
        out.append("\t}")
        out.append("}")
    out.append("")
    out.append("# Any other host name that reaches the proxy (e.g. by IP) is not ours.")
    out.append(":80 {")
    out.append('\trespond "Unknown host" 404')
    out.append("}")
    return "\n".join(out) + "\n"


def dnsmasq(inv):
    edge = edge_node(inv)
    e = inv["nodes"][edge]
    dom = inv["domain"]
    lines = [
        "# Generated by fleet/edge/render.py. Answers the inventory's %s names for the tailnet." % dom,
        "port=53",
        "listen-address=%s" % e["tailscale_ip"],
        "bind-dynamic",
        "no-resolv",
        "no-hosts",
        "no-poll",
        "domain-needed",
        "bogus-priv",
        "user=nobody",
        "group=nogroup",
        "# Authoritative for the domain: names not listed below get NXDOMAIN.",
        "local=/%s/" % dom,
    ]
    # Portal and service names go to the edge proxy; each machine's own name points
    # straight at it (that wins if a node name is also a portal name).
    records = {dom: e["tailscale_ip"]}
    for n in inv["portal"]["names"]:
        records["%s.%s" % (n, dom)] = e["tailscale_ip"]
    for svc in inv["services"]:
        if svc.get("name_host"):
            records["%s.%s" % (svc["name_host"], dom)] = e["tailscale_ip"]
    for name, node in inv["nodes"].items():
        records["%s.%s" % (name, dom)] = node["tailscale_ip"]
    for name in sorted(records):
        lines.append("host-record=%s,%s" % (name, records[name]))
    return "\n".join(lines) + "\n"


def mdns_hosts(inv):
    names = ["%s.local" % n for n in inv["portal"]["local_names"]]
    names += ["%s.local" % s["name_host"] for s in inv["services"] if s.get("name_host")]
    seen = []
    for n in names:
        if n not in seen:
            seen.append(n)
    return "\n".join(seen) + "\n"


def portal_inventory(inv):
    """Inventory as served to the browser (no SSH aliases or paths)."""
    nodes = {}
    for name, n in inv["nodes"].items():
        nodes[name] = {k: n[k] for k in ("title", "role", "os", "lan_ip", "tailscale_ip", "controls") if k in n}
    services = []
    for s in inv["services"]:
        if s.get("monitor", True):
            services.append({k: s[k] for k in ("id", "name", "desc", "node", "name_host", "optional", "stack") if k in s})
    return json.dumps({"domain": inv["domain"], "nodes": nodes, "services": services}, indent=2) + "\n"


def main():
    inv = load()
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "edge")
    os.makedirs(out, exist_ok=True)
    files = {
        "Caddyfile": caddyfile(inv),
        "dnsmasq.conf": dnsmasq(inv),
        "mdns-hosts": mdns_hosts(inv),
        "inventory.json": portal_inventory(inv),
    }
    for name, body in files.items():
        with open(os.path.join(out, name), "w") as f:
            f.write(body)
    print("rendered %s -> %s" % (", ".join(files), out))


if __name__ == "__main__":
    main()
